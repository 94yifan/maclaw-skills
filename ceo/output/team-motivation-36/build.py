def load(n):
    with open(os.path.join(P, "%s.md" % n), encoding="utf-8") as f:
        t = f.read()
    notes = re.findall(r"<!--(.*?)-->", t, re.S)
    t = re.sub(r"<!--.*?-->", "", t, flags=re.S).strip()
    note = " ".join(x.strip() for x in notes)
    note = re.sub(r"^注：", "", note).strip()
    return t, note

def page(n, label):
    t, note = load(n)
    out = ["**〔%s〕**\n" % label]
    if note:
        out.append("> *校注：%s*\n" % note.replace("\n", " ").strip())
    out.append(t + "\n")
    return "\n".join(out)

